update public.book_types
set sort_order = case
  when lower(name) like '%single parent%' or name like '%한부모%' then 2
  when lower(name) like '%single%' or name like '%싱글%' then 3
  when lower(name) like '%couple%' or name like '%커플%' or name like '%부부%' then 4
  when lower(name) like '%parent%' or name like '%부모%' then 1
  else coalesce(sort_order, id)
end
where sort_order = 1;

