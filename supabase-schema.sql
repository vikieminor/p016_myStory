where not exists (select 1 from public.question_book_types);

select setval(pg_get_serial_sequence('public.book_types', 'id'), coalesce((select max(id) from public.book_types), 1), true);

select setval(
  pg_get_serial_sequence('public.questions', 'id'),
  coalesce((select max(id) from public.questions), 1),
  true
);
